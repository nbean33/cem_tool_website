"""Build the website's WebAssembly tools into tools/ (which is committed and served by Pages).

Usage:
  python scripts/build_tools.py            # test, build both tools, regenerate the calculator list
  python scripts/build_tools.py --skip-tests
  python scripts/build_tools.py --list-only  # only regenerate assets/pcb-calcs.js

Steps:
  1. cargo test on tools-src/rust (the vendored crates plus pcb-wasm and nec-wasm), natively.
  2. wasm-pack builds pcb-wasm and nec-wasm into each app's src tree.
  3. npm install + npm run build for each app; Vite writes tools/pcb and tools/antenna.
  4. assets/pcb-calcs.js: every pcb_toolkit calculator (id, name, group, blurb) for the
     RF Calculators page, read from the same calculators.ts schema the app uses.

Needs: Rust with the wasm32-unknown-unknown target, wasm-pack, Node.js. Run
scripts/sync_vendor.py first after changing the source repos.
"""
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOLS = ROOT / "tools-src"
RUST = TOOLS / "rust"


def run(cmd: list, cwd: pathlib.Path):
    print(f"\n$ {' '.join(cmd)}   (in {cwd.relative_to(ROOT)})", flush=True)
    exe = shutil.which(cmd[0]) or cmd[0]  # npm is npm.cmd on Windows
    result = subprocess.run([exe, *cmd[1:]], cwd=cwd)
    if result.returncode:
        sys.exit(f"failed: {' '.join(cmd)}")


def pcb_calculator_list():
    """assets/pcb-calcs.js from the PCB Toolkit schema."""
    schema = (TOOLS / "pcb-app/src/schema/calculators.ts").read_text(encoding="utf-8")
    body = schema[schema.index("export const CALCULATORS"):]

    def string_value(key: str, chunk: str) -> str:
        # A key's value is one string literal or several joined with `+` across lines.
        m = re.search(rf"\b{key}:\s*((?:\"(?:[^\"\\]|\\.)*\"\s*\+?\s*)+)", chunk)
        if not m:
            return ""
        return "".join(json.loads(s) for s in re.findall(r"\"(?:[^\"\\]|\\.)*\"", m.group(1)))

    calcs = []
    starts = [m.start() for m in re.finditer(r"\bid:\s*\"", body)]
    for i, start in enumerate(starts):
        chunk = body[start: starts[i + 1] if i + 1 < len(starts) else len(body)]
        fields_at = chunk.find("fields:")
        head = chunk[: fields_at if fields_at > 0 else len(chunk)]
        calcs.append({k: string_value(k, head) for k in ("id", "name", "group", "blurb")})
    if len(calcs) < 40 or any(not c["id"] or not c["name"] for c in calcs):
        sys.exit(f"calculators.ts parse looks wrong: {len(calcs)} calculators")
    out = ROOT / "assets/pcb-calcs.js"
    out.write_text(
        "// Generated by scripts/build_tools.py from tools-src/pcb-app/src/schema/calculators.ts.\n"
        f"window.PCB_CALCS = {json.dumps(calcs, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)}: {len(calcs)} calculators")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skip-tests", action="store_true")
    ap.add_argument("--list-only", action="store_true")
    args = ap.parse_args()
    if args.list_only:
        pcb_calculator_list()
        return
    if not args.skip_tests:
        run(["cargo", "test", "--workspace", "--quiet"], RUST)
    run(["wasm-pack", "build", "pcb-wasm", "--target", "web", "--release", "--no-pack",
         "--out-dir", "../../pcb-app/src/wasm"], RUST)
    run(["wasm-pack", "build", "nec-wasm", "--target", "web", "--release", "--no-pack",
         "--out-dir", "../../nec-app/src/lib/wasm"], RUST)
    for app in ("pcb-app", "nec-app"):
        run(["npm", "install", "--no-audit", "--no-fund"], TOOLS / app)
        run(["npm", "run", "build"], TOOLS / app)
    pcb_calculator_list()
    print("\nBuilt tools/pcb and tools/antenna. Commit tools/ and assets/pcb-calcs.js.")


if __name__ == "__main__":
    main()
